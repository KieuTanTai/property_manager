-- Payment module schema.
-- Payment owns this table only and deliberately shares the database already used by the other
-- modules (ms_identity_test). There are no foreign keys to monthly_invoice / account: the link
-- is logical only (payment_invoice_id / payment_account_id) so that modules stay decoupled.
-- Run against the database created by docs/sql/demo_project.sql.

USE `ms_identity_test`;

CREATE TABLE IF NOT EXISTS `payment_transaction`
(
    `payment_transaction_id`             UUID           NOT NULL DEFAULT (UUID_v7()),
    `payment_invoice_id`                 UUID           NOT NULL,
    `payment_account_id`                 UUID           NOT NULL,
    `payment_amount`                     DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    `payment_status`                     ENUM (
        'pending',
        'succeeded',
        'failed',
        'expired',
        'needsreview'
        )                                                NOT NULL DEFAULT 'pending',
    `payment_currency`                   VARCHAR(3)     NOT NULL DEFAULT 'VND',
    `payment_txn_ref`                    VARCHAR(50)    NULL,
    `payment_gateway_transaction_number` VARCHAR(100)   NULL,
    `payment_bank_code`                  VARCHAR(20)    NULL,
    `payment_bank_tran_no`               VARCHAR(100)   NULL,
    `payment_response_code`              VARCHAR(10)    NULL,
    `payment_transaction_status_code`    VARCHAR(10)    NULL,
    `payment_card_type`                  VARCHAR(50)    NULL,
    `payment_order_info`                 VARCHAR(255)   NULL,
    `payment_pay_date`                   TIMESTAMP      NULL,
    `payment_expires_at`                 TIMESTAMP      NOT NULL,
    `payment_created_at`                 TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `payment_updated_at`                 TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (`payment_transaction_id`),

    -- vnp_TxnRef is generated by this module (DateTime.UtcNow.Ticks) and must be unique per
    -- transaction; it is the key an IPN comes back with.
    UNIQUE KEY `uk_payment_txn_ref` (`payment_txn_ref`),

    INDEX `idx_payment_invoice_id` (`payment_invoice_id`),
    INDEX `idx_payment_account_id` (`payment_account_id`),
    INDEX `idx_payment_status` (`payment_status`),
    INDEX `idx_payment_created_at` (`payment_created_at`)
) ENGINE = InnoDB;

